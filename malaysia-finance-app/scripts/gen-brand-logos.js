// Builds src/ui/brandLogos.ts from the image files in assets/brands/ (see the README there).
// Metro needs static require() calls, so the list is generated; `npm start`, `npm run web` and `npm test` run this first.
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'assets', 'brands');
const out = path.join(__dirname, '..', 'src', 'ui', 'brandLogos.ts');
const files = fs.existsSync(dir)
  ? fs.readdirSync(dir).filter((f) => /^[a-z0-9-]+\.(png|jpe?g|webp)$/.test(f)).sort()
  : [];

const lines = files.map((f) => `  '${f.replace(/\.[^.]+$/, '')}': require('../../assets/brands/${f}'),`);
const body = `// Generated by scripts/gen-brand-logos.js from assets/brands/. Do not edit by hand.
import type { ImageSourcePropType } from 'react-native';

export const BRAND_LOGOS: Record<string, ImageSourcePropType> = {
${lines.join('\n')}
};
`;
if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== body) fs.writeFileSync(out, body);
console.log(`brand logos: ${files.length} file(s) from assets/brands`);
